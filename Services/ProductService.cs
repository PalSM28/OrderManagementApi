using System.Linq.Expressions;
using Microsoft.EntityFrameworkCore;
using OrderManagement.Data;
using OrderManagement.Domain;
using OrderManagement.Dtos;
using OrderManagement.Entity;

namespace OrderManagement.Services
{
    public class ProductService : IProductService
    {
        //private readonly IProductRepository _productRepository;
        //private readonly IMapper _mapper;

        private readonly AppDbContext _dbContext;

        private HashSet<int>? _categoryIds;   // per-request cache (service is Scoped)

        public ProductService(AppDbContext dbContext)
        {
            _dbContext = dbContext;
        }

        private static readonly Expression<Func<Product, ProductDto>> ToDto = p => new ProductDto
        {
            Id = p.Id,
            Name = p.Name,
            Sku = p.Sku,
            Price = p.Price,
            Stock = p.Stock,
            CategoryId = p.CategoryId,
            CategoryName = p.Category.Name,   // JOIN generated by EF
            RowVersion = p.RowVersion
        };

        public async Task<PagedResult<ProductDto>> GetPagedAsync(ProductQuery query, CancellationToken ct)
        {
            var page = Math.Max(query.Page, 1);
            var size = Math.Clamp(query.PageSize, 1, 100);

            var products = _dbContext.Products.AsNoTracking();

            if (query.CategoryId is int categoryId)
                products = products.Where(p => p.CategoryId == categoryId);

            var search = query.Search?.Trim();
            if (!string.IsNullOrEmpty(search))
                products = products.Where(p => p.Name.Contains(search));

            var total = await products.CountAsync(ct);
            var items = await products
                                .OrderBy(p => p.Id)
                                .Skip((page - 1) * size)
                                .Take(size)
                                .Select(ToDto)
                                .ToListAsync(ct);
            //return new PagedResult<ProductDto>(items, total);
            return new PagedResult<ProductDto> { Items = items, Page = page, PageSize = size, TotalCount = total };
        }

        // C# 8: async stream - rows are produced one by one instead of buffering a full list
        public async IAsyncEnumerable<ProductDto> StreamAsync(CancellationToken ct)
        {
            var query = _dbContext.Products.AsNoTracking().OrderBy(p => p.Id).Select(ToDto);

            await foreach (var product in query.AsAsyncEnumerable().WithCancellation(ct))
                yield return product;
        }

        public async Task<ProductDto> GetAsync(int id, CancellationToken ct)
        {
            var dto = await _dbContext.Products
            .AsNoTracking()
            .Where(p => p.Id == id)
            .Select(ToDto)
            .FirstOrDefaultAsync(ct);
            return dto ?? throw new NotFoundException(nameof(Product), id);
        }

        public async Task<string> GetAuditAsync(int id, CancellationToken ct)
        {
            var product = await _dbContext.Products.AsNoTracking().FirstOrDefaultAsync(p => p.Id == id, ct)
                          ?? throw new NotFoundException(nameof(Product), id);

            IAuditable auditable = (IAuditable)product;   // default interface members are only visible through the interface type
            return auditable.Describe();
        }

        public async Task<ProductDto> CreateAsync(ProductWriteDto dto, CancellationToken ct)
        {
            await EnsureCategoryExistsAsync(dto.CategoryId, ct);

            var sku = NormalizeSku(dto.Sku);
            if (await _dbContext.Products.AnyAsync(p => p.Sku == sku, ct))
                throw new ConflictException($"SKU '{sku}' already exists.");

            var product = Build(dto, sku);
            _dbContext.Products.Add(product);
            await _dbContext.SaveChangesAsync(ct);

            return await GetAsync(product.Id, ct);

            // C# 8: static local function - cannot capture locals/fields by accident
            static Product Build(ProductWriteDto d, string normalizedSku) => new Product
            {
                Name = d.Name.Trim(),
                Sku = normalizedSku,
                Price = d.Price,
                Stock = d.Stock,
                CategoryId = d.CategoryId
            };
        }

        public async Task<ProductDto> UpdateAsync(int id, ProductWriteDto dto, CancellationToken ct)
        {
            var product = await _dbContext.Products.FirstOrDefaultAsync(p => p.Id == id, ct)
                          ?? throw new NotFoundException(nameof(Product), id);

            await EnsureCategoryExistsAsync(dto.CategoryId, ct);

            var sku = NormalizeSku(dto.Sku);
            if (await _dbContext.Products.AnyAsync(p => p.Sku == sku && p.Id != id, ct))
                throw new ConflictException($"SKU '{sku}' already exists.");

            // Optimistic concurrency: compare against the version the client last saw
            if (dto.RowVersion != null)
                _dbContext.Entry(product).Property(p => p.RowVersion).OriginalValue = dto.RowVersion;

            product.Name = dto.Name.Trim();
            product.Sku = sku;
            product.Price = dto.Price;
            product.Stock = dto.Stock;
            product.CategoryId = dto.CategoryId;

            await _dbContext.SaveChangesAsync(ct);   // DbUpdateConcurrencyException -> HTTP 409 via middleware
            return await GetAsync(id, ct);
        }

        public async Task DeleteAsync(int id, CancellationToken ct)
        {
            var product = await _dbContext.Products.FirstOrDefaultAsync(p => p.Id == id, ct)
                          ?? throw new NotFoundException(nameof(Product), id);

            if (await _dbContext.OrderItems.AnyAsync(i => i.ProductId == id, ct))
                throw new BusinessRuleException("Cannot delete a product that appears in orders.");

            _dbContext.Products.Remove(product);
            await _dbContext.SaveChangesAsync(ct);
        }

        private static string NormalizeSku(string sku) => sku.Trim().ToUpperInvariant();

        private async Task EnsureCategoryExistsAsync(int categoryId, CancellationToken ct)
        {
            // C# 8: null-coalescing assignment - load once per request, then reuse
            _categoryIds ??= new HashSet<int>(await _dbContext.Categories.AsNoTracking().Select(c => c.Id).ToListAsync(ct));

            if (!_categoryIds.Contains(categoryId))
                throw new NotFoundException(nameof(Category), categoryId);
        }
    }
}